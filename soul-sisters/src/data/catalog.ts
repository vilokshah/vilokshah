const sizesOne = ['OS']

function variants(
  prefix: string,
  sizes: string[],
  colors: string[],
  stock: number,
): Product['variants'] {
  const out: Product['variants'] = []
  colors.forEach((color, ci) => {
    sizes.forEach((size, si) => {
      const sku = `${prefix}-${color.slice(0, 3).toUpperCase()}-${size}`
      out.push({
        size,
        color,
        sku,
        barcode: `890${(ci + 1)}${(si + 1)}${prefix.replace(/\D/g, '').padStart(6, '7')}`.slice(0, 13).padEnd(13, '0'),
        stock: stock + ((ci + si) % 4),
      })
    })
  })
  return out
}

